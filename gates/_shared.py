"""Pieces shared by the gate scripts.

`gate_0.py` keeps its own copies of these on purpose: it was committed before this
module existed, and rule 3.4.5 says a gate script may be changed only with a written
rationale. Refactoring a passing gate for tidiness is not a reason. New gates import
from here instead, so the duplication stops growing.
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal

REPO_ROOT = Path(__file__).resolve().parent.parent
THRESHOLDS_PATH = REPO_ROOT / "config" / "thresholds.yaml"
REPORTS_DIR = REPO_ROOT / "reports"

Status = Literal["PASS", "FAIL", "WARN", "NEEDS_HUMAN"]

# Prompt Section 3.2. A report or API string containing one of these, used as an
# assertion about an address or entity rather than as a quotation of the rule, fails
# the language audit.
BANNED_TERMS = ("scam", "fraud", "fake", "criminal", "wash trader", "wash-trading")


@dataclass
class CheckResult:
    id: str
    title: str
    status: Status
    measured: str
    threshold: str
    evidence: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


def load_thresholds() -> dict[str, Any]:
    import yaml

    if not THRESHOLDS_PATH.is_file():
        raise SystemExit(f"FATAL: {THRESHOLDS_PATH} is missing")
    with THRESHOLDS_PATH.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
    return data


def git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return out.stdout.strip() if out.returncode == 0 else "unknown"


def git_dirty_paths(paths: list[str] | None = None) -> list[str]:
    """Uncommitted changes, optionally restricted to the source paths a gate measures.

    F12: the gate report claimed a commit that did not contain the code it measured.
    Reports are regenerated by the gate itself, so they are excluded by passing only
    the source paths here; anything else is a provenance failure.
    """
    cmd = ["git", "status", "--porcelain"]
    if paths:
        cmd += ["--", *paths]
    try:
        out = subprocess.run(
            cmd,
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return ["git status could not be run"]
    if out.returncode != 0:
        return ["git status failed"]
    return [line for line in out.stdout.splitlines() if line.strip()]


def sha256_file(path: Path) -> str | None:
    if not path.is_file():
        return None
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def rel(path: Path) -> str:
    try:
        return path.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path)


def read_json(path: Path) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    try:
        with path.open(encoding="utf-8") as fh:
            loaded = json.load(fh)
    except (json.JSONDecodeError, OSError):
        return None
    return loaded if isinstance(loaded, dict) else None


def run(cmd: list[str], timeout: int = 900) -> tuple[int, str]:
    """Run a command, returning (exit code, combined output). Never raises on failure."""
    try:
        proc = subprocess.run(
            cmd,
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return 1, f"{type(exc).__name__}: {exc}"
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def snapshot_hash(paths: list[Path]) -> str:
    parts = [f"{rel(p)}={sha256_file(p) or 'MISSING'}" for p in paths]
    return hashlib.sha256("\n".join(parts).encode()).hexdigest()


_REVIEW_NAME = re.compile(r"review_[A-Za-z](\d*)\.md$")


def _review_order(path: Path) -> tuple[int, str]:
    """Order review files by their number, not by their characters (I5).

    `sorted()` is lexicographic, so `review_B10.md` sorts before `review_B2.md`. Once
    ten reviews existed, `newest_review` would have handed GB.11 a superseded report
    and a newer review's findings could have been ignored. A review with no number
    (`review_B.md`) is the first one and orders as 0.
    """
    match = _REVIEW_NAME.fullmatch(path.name)
    number = match.group(1) if match else ""
    return (int(number) if number else 0, path.name)


def newest_review(prefix: str) -> tuple[Path, list[Path]]:
    """Newest reports/review_<prefix>*.md, so a later review always supersedes."""
    found = sorted(REPORTS_DIR.glob(f"review_{prefix}*.md"), key=_review_order)
    if not found:
        return REPORTS_DIR / f"review_{prefix}.md", []
    return found[-1], found


def write_reports(
    gate_id: str,
    results: list[CheckResult],
    *,
    commit: str,
    snapshot: str,
    extra: dict[str, Any] | None = None,
) -> tuple[Path, Path]:
    generated = datetime.now(UTC).isoformat(timespec="seconds")
    md_path = REPORTS_DIR / f"gate_{gate_id}.md"
    json_path = REPORTS_DIR / f"gate_{gate_id}.json"

    lines: list[str] = []
    lines.append(f"# Gate {gate_id}")
    lines.append("")
    lines.append(f"Generated by `make gate-{gate_id}`. **Do not edit by hand.**")
    lines.append("")
    lines.append(f"- **Generated:** {generated}")
    lines.append(f"- **Commit:** `{commit}`")
    lines.append(f"- **Data snapshot hash:** `{snapshot}`")
    if extra and "source_tree_clean" in extra:
        state = "clean" if extra["source_tree_clean"] else "DIRTY"
        lines.append(f"- **Source tree:** {state}")
    lines.append("")
    lines.append("## Result table")
    lines.append("")
    lines.append("| ID | Status | Check | Measured | Threshold |")
    lines.append("|---|---|---|---|---|")
    for r in results:
        lines.append(f"| {r.id} | **{r.status}** | {r.title} | {r.measured} | {r.threshold} |")
    lines.append("")

    counts: dict[str, int] = {}
    for r in results:
        counts[r.status] = counts.get(r.status, 0) + 1
    lines.append("**Summary:** " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    lines.append("")

    lines.append("## Detail")
    lines.append("")
    for r in results:
        lines.append(f"### {r.id} — {r.status}")
        lines.append("")
        lines.append(f"**{r.title}**")
        lines.append("")
        lines.append(f"- Measured: {r.measured}")
        lines.append(f"- Threshold: {r.threshold}")
        if r.evidence:
            lines.append(f"- Evidence: {', '.join(f'`{e}`' for e in r.evidence)}")
        for note in r.notes:
            lines.append(f"- Note: {note}")
        lines.append("")

    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text("\n".join(lines), encoding="utf-8")

    payload: dict[str, Any] = {
        "gate": gate_id,
        "generated": generated,
        "commit": commit,
        "data_snapshot_hash": snapshot,
        "checks": [
            {
                "id": r.id,
                "title": r.title,
                "status": r.status,
                "measured": r.measured,
                "threshold": r.threshold,
                "evidence": r.evidence,
                "notes": r.notes,
            }
            for r in results
        ],
        "summary": {
            status: sum(1 for r in results if r.status == status)
            for status in ("PASS", "FAIL", "WARN", "NEEDS_HUMAN")
        },
    }
    if extra:
        payload.update(extra)
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return md_path, json_path


def main_wrapper(
    gate_id: str,
    checks: list[Any],
    snapshot_paths: list[Path],
    *,
    source_paths: list[str] | None = None,
    extra: dict[str, Any] | None = None,
) -> int:
    thresholds = load_thresholds()
    commit = git_commit()

    # Source provenance is captured before any check runs: a check that rewrote source
    # would otherwise be measured as clean. F12 was exactly this failure.
    dirty = git_dirty_paths(source_paths)
    report_extra = dict(extra or {})
    report_extra["source_tree_clean"] = not dirty
    if dirty:
        report_extra["dirty_source_paths"] = dirty

    results: list[CheckResult] = []
    for check in checks:
        try:
            results.append(check(thresholds))
        except Exception as exc:  # noqa: BLE001 - a crashing check must not read as a pass
            name = check.__name__.replace("check_", "").upper()
            results.append(
                CheckResult(
                    id=name,
                    title=(check.__doc__ or name).splitlines()[0],
                    status="FAIL",
                    measured=f"check raised {type(exc).__name__}",
                    threshold="check must complete",
                    notes=[str(exc)],
                )
            )

    # The snapshot is hashed *after* the checks finish. The checks regenerate the very
    # artifacts this list names, so a pre-run hash describes files the run replaces and
    # cannot be reproduced from the committed evidence (second review, G5). The gate
    # report files are not in the list, so writing them below does not move the hash.
    snapshot = snapshot_hash(snapshot_paths)

    md_path, json_path = write_reports(
        gate_id, results, commit=commit, snapshot=snapshot, extra=report_extra
    )

    print(f"wrote {rel(md_path)} and {rel(json_path)}")
    for r in results:
        print(f"  {r.id:<7} {r.status:<12} {r.measured}")

    blocking = [r for r in results if r.status in ("FAIL", "NEEDS_HUMAN")]
    if blocking:
        print(f"\nGATE {gate_id} DID NOT PASS ({len(blocking)} blocking check(s)).")
        return 1
    print(f"\nGATE {gate_id} PASSED.")
    return 0
